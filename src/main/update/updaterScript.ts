// src/main/update/updaterScript.ts - the folder-swap installer (v5 W2, spec 2.2 "Install"). UPDATER_SCRIPT is written verbatim to
// <userData>\updates\<version>\updater.cjs and run by the NEW build's own exe as Node (ELECTRON_RUN_AS_NODE=1), detached, after
// the old app has quit. It is plain CommonJS over node:fs / node:path / node:child_process only, and it never downloads, never
// evaluates input, and never launches anything but `<installDir>\<exeName>` (the new build, or the old one on a rollback).
//
// argv (after the runtime and the script path), see updaterArgs():
//   0 pid        the old app's pid; waited for up to 60 s (process.kill(pid, 0) polling)
//   1 installDir the folder of the running app (path.dirname(app.getPath('exe')))
//   2 stagedDir  the verified, extracted new build (<userData>\updates\<version>\win-unpacked)
//   3 exeName    the exe file name inside both folders
//   4 logFile    <userData>\logs\updater.log (appended; events + numbers only, never a path or URL)
//   5 from       the running version     6 to   the staged version
//   7 waitMs     (tests only, optional) pid wait, clamped to [10, 60000]
//   8 retryMs    (tests only, optional) delay between the 10 rename attempts, clamped to [10, 1000]
// Exit codes: UPDATER_EXIT below. Every failure after the old app exited ends with the OLD build running `--update-failed <to>`.
//
// Review fix pass: before any rename the script repeats main's canInstall folder rule (updatePolicy.ts, embedded below as
// data): installDir AND stagedDir must each hold a packaged build and nothing else, and installDir may not be a drive root,
// the profile, Desktop, Downloads or Documents. A previous `.old-*` build is only ever deleted when it passes the same rule.
// The relaunched app gets the same minimal environment as the updater, without ELECTRON_RUN_AS_NODE.
// When `require`d instead of run (tests), the script exports its rule functions and does nothing else.
import {
  PACKAGED_REQUIRED_FILES,
  PACKAGED_ROOT_DIRS,
  PACKAGED_ROOT_FILES,
  PROTECTED_PROFILE_SUBDIRS,
  UPDATER_ENV_KEYS,
} from './updatePolicy';

export const UPDATER_EXIT = {
  ok: 0,
  /** argv invalid or a folder / exe missing: nothing touched, nothing launched. */
  badArgs: 2,
  /** the old process did not exit within the wait: nothing touched, nothing launched (it is still running). */
  oldStillRunning: 3,
  /** installDir could not be moved aside (locked): nothing changed; old build relaunched with --update-failed. */
  installLocked: 4,
  /** the staged build could not be moved into place: rolled back; old build relaunched with --update-failed. */
  swapFailed: 5,
  /** a rollback step failed: logged; whatever exe is at installDir is started with --update-failed. */
  rollbackFailed: 6,
  /** the new exe could not be started: rolled back; old build relaunched with --update-failed. */
  relaunchFailed: 7,
  /** installDir or stagedDir is not exactly a packaged build (or installDir is a protected folder): nothing touched; the old
   *  build is relaunched with --update-failed when its exe is there. */
  notAnInstallDir: 8,
} as const;
export type UpdaterExitCode = (typeof UPDATER_EXIT)[keyof typeof UPDATER_EXIT];

/** The script's argv after its own path (main passes exactly these seven). */
export function updaterArgs(input: {
  pid: number;
  installDir: string;
  stagedDir: string;
  exeName: string;
  logFile: string;
  from: string;
  to: string;
}): string[] {
  return [String(input.pid), input.installDir, input.stagedDir, input.exeName, input.logFile, input.from, input.to];
}

export const UPDATER_SCRIPT = String.raw`'use strict';
// WhatsApp Calendar Agent folder-swap updater (generated by src/main/update/updaterScript.ts; do not edit).
// Plain node:fs on purpose (the one exemption from src/main/update/fsReal.ts): this script must need nothing but Node
// built-ins. NOTE: Electron's asar patch is NOT off under ELECTRON_RUN_AS_NODE - checked 2026-10-20 with Electron 44.4.3:
// statSync('<dir>\resources\app.asar') throws "Invalid package". So this script never stats an .asar path: "is a file" comes
// from readdirSync(withFileTypes) of the parent, and the folder moves use renameSync / rmSync / cpSync, which the same check
// showed working on a folder holding an app.asar (Dirent type correct, copy + rename + recursive delete complete).
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');

const EXIT = { ok: 0, badArgs: 2, oldStillRunning: 3, installLocked: 4, swapFailed: 5, rollbackFailed: 6, relaunchFailed: 7, notAnInstallDir: 8 };
const POLICY = ${JSON.stringify({
  dirs: PACKAGED_ROOT_DIRS,
  files: PACKAGED_ROOT_FILES.map((re) => re.source),
  required: PACKAGED_REQUIRED_FILES,
  protectedSubdirs: PROTECTED_PROFILE_SUBDIRS,
  envKeys: UPDATER_ENV_KEYS,
})};
const FILE_RES = POLICY.files.map(function (src) {
  return new RegExp(src, 'i');
});
const VERSION_RE = /^\d{1,6}\.\d{1,6}\.\d{1,6}$/;
const ATTEMPTS = 10;

const argv = require.main === module ? process.argv.slice(2) : [];
const logFile = typeof argv[4] === 'string' && path.isAbsolute(argv[4]) ? argv[4] : null;

function log(event, meta) {
  if (logFile === null) return;
  let line = new Date().toISOString() + ' ' + event;
  for (const k of Object.keys(meta || {})) line += ' ' + k + '=' + String(meta[k]);
  try {
    fs.mkdirSync(path.dirname(logFile), { recursive: true });
    fs.appendFileSync(logFile, line + '\n');
  } catch (e) {
    /* logging is best effort */
  }
}
function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}
function clampInt(raw, min, max, dflt) {
  const n = Number(raw);
  if (!Number.isInteger(n)) return dflt;
  return Math.min(max, Math.max(min, n));
}
function isAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (e) {
    return e && e.code === 'EPERM';
  }
}
function exists(p) {
  try {
    fs.statSync(p);
    return true;
  } catch (e) {
    return false;
  }
}
function isFile(p) {
  try {
    return fs.statSync(p).isFile();
  } catch (e) {
    return false;
  }
}
function isDir(p) {
  try {
    return fs.statSync(p).isDirectory();
  } catch (e) {
    return false;
  }
}
function inside(child, parent) {
  const rel = path.relative(parent, child);
  return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
}
/** fs.renameSync with ATTEMPTS tries (OneDrive / antivirus hold files for a moment). Returns the last error code or null. */
function renameWithRetry(from, to, retryMs, what) {
  let last = null;
  for (let i = 1; i <= ATTEMPTS; i += 1) {
    try {
      fs.renameSync(from, to);
      return null;
    } catch (e) {
      last = (e && e.code) || 'unknown';
      log('rename_retry', { what: what, attempt: i, code: last });
      if (last === 'EXDEV') return last;
      if (i < ATTEMPTS) sleep(retryMs);
    }
  }
  return last;
}
/** staged -> installDir; a different volume (EXDEV) falls back to copy + delete. */
function moveStaged(from, to, retryMs) {
  const code = renameWithRetry(from, to, retryMs, 'staged');
  if (code === null) return true;
  if (code !== 'EXDEV') return false;
  try {
    fs.cpSync(from, to, { recursive: true, errorOnExist: true, force: false });
    try {
      fs.rmSync(from, { recursive: true, force: true, maxRetries: 3 });
    } catch (e) {
      /* the staged copy is cleaned up by the next app start */
    }
    log('copied_across_volumes', {});
    return true;
  } catch (e) {
    log('copy_failed', { code: (e && e.code) || 'unknown' });
    try {
      fs.rmSync(to, { recursive: true, force: true, maxRetries: 3 });
    } catch (e2) {
      /* rollback below reports it */
    }
    return false;
  }
}
// ---- the folder rule and the environment (same lists as src/main/update/updatePolicy.ts) ----
function norm(p) {
  return path.resolve(p).replace(/[\\/]+$/, '').toLowerCase();
}
function protectedDirs(env) {
  const out = [];
  const home = env.USERPROFILE;
  if (typeof home === 'string' && home !== '' && path.isAbsolute(home)) {
    out.push(home);
    for (const sub of POLICY.protectedSubdirs) out.push(path.join.apply(path, [home].concat(sub.split('/'))));
  }
  return out;
}
function pathRefusal(dir, prot) {
  if (typeof dir !== 'string' || !path.isAbsolute(dir)) return 'not_absolute';
  const n = norm(dir);
  if (n === norm(path.parse(path.resolve(dir)).root)) return 'drive_root';
  for (const p of prot) if (norm(p) === n) return 'protected_path';
  return null;
}
function isPackagedRootEntry(name, kind, exeName) {
  if (kind === 'dir') {
    for (const d of POLICY.dirs) if (d.toLowerCase() === name.toLowerCase()) return true;
    return false;
  }
  if (kind !== 'file') return false;
  if (name.toLowerCase() === exeName.toLowerCase()) return true;
  for (const re of FILE_RES) if (re.test(name)) return true;
  return false;
}
/** From the parent's listing, never stat(): Electron's asar patch (active here too) makes stat('app.asar') throw. */
function listedAsFile(parent, name) {
  try {
    return fs.readdirSync(parent, { withFileTypes: true }).some(function (e) {
      return e.name === name && e.isFile();
    });
  } catch (e) {
    return false;
  }
}
/** null = a packaged build and nothing else; otherwise the refusal reason. */
function inspectInstallDir(dir, exeName, prot) {
  const byPath = pathRefusal(dir, prot);
  if (byPath !== null) return byPath;
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (e) {
    return 'unreadable';
  }
  for (const e of entries) {
    const kind = e.isSymbolicLink() ? 'other' : e.isDirectory() ? 'dir' : e.isFile() ? 'file' : 'other';
    if (!isPackagedRootEntry(e.name, kind, exeName)) return 'foreign_entry';
  }
  const exeListed = entries.some(function (e) {
    return e.name === exeName && e.isFile();
  });
  if (!exeListed) return 'exe_missing';
  for (const rel of POLICY.required) {
    const segs = rel.split('/');
    const name = segs.pop();
    if (!listedAsFile(path.join.apply(path, [dir].concat(segs)), name)) return 'asar_missing';
  }
  return null;
}
function minimalEnv(src, runAsNode) {
  const upper = new Map();
  for (const k of Object.keys(src)) {
    const v = src[k];
    if (typeof v === 'string' && !upper.has(k.toUpperCase())) upper.set(k.toUpperCase(), v);
  }
  const out = {};
  for (const k of POLICY.envKeys) {
    const v = upper.get(k.toUpperCase());
    if (v !== undefined && v !== '') out[k] = v;
  }
  const root = out.SystemRoot !== undefined ? out.SystemRoot : out.windir;
  if (root !== undefined) out.PATH = root.replace(/[\\/]+$/, '') + '\\System32';
  if (runAsNode) out.ELECTRON_RUN_AS_NODE = '1';
  return out;
}
/** Deletes a previous build only when it passes the folder rule; true when it is gone. */
function removeOldBuild(dir, exeName, prot) {
  const why = inspectInstallDir(dir, exeName, prot);
  if (why !== null) {
    log('old_build_kept', { reason: why });
    return false;
  }
  try {
    fs.rmSync(dir, { recursive: true, force: true, maxRetries: 3 });
  } catch (e) {
    /* reported through exists() below */
  }
  return !exists(dir);
}
function launch(dir, exeName, args, mode) {
  const exe = path.join(dir, exeName);
  if (!isFile(exe)) {
    log('relaunch', { mode: mode, ok: false, reason: 'exe_missing' });
    return Promise.resolve(false);
  }
  return new Promise(function (resolve) {
    let child;
    try {
      child = cp.spawn(exe, args, {
        cwd: dir,
        detached: true,
        stdio: 'ignore',
        windowsHide: false,
        env: minimalEnv(process.env, false),
      });
    } catch (e) {
      log('relaunch', { mode: mode, ok: false, reason: (e && e.code) || 'spawn_threw' });
      resolve(false);
      return;
    }
    child.once('spawn', function () {
      log('relaunch', { mode: mode, ok: true });
      child.unref();
      resolve(true);
    });
    child.once('error', function (e) {
      log('relaunch', { mode: mode, ok: false, reason: (e && e.code) || 'spawn_error' });
      resolve(false);
    });
  });
}

async function main() {
  const pid = Number(argv[0]);
  const installDir = argv[1];
  const stagedDir = argv[2];
  const exeName = argv[3];
  const from = argv[5];
  const to = argv[6];
  const waitMs = clampInt(argv[7], 10, 60000, 60000);
  const retryMs = clampInt(argv[8], 10, 1000, 1000);
  log('updater_start', { from: from, to: to });

  const valid =
    Number.isInteger(pid) && pid > 0 && pid !== process.pid &&
    typeof installDir === 'string' && path.isAbsolute(installDir) && path.parse(installDir).root !== path.resolve(installDir) &&
    typeof stagedDir === 'string' && path.isAbsolute(stagedDir) && path.parse(stagedDir).root !== path.resolve(stagedDir) &&
    !inside(path.resolve(stagedDir), path.resolve(installDir)) && !inside(path.resolve(installDir), path.resolve(stagedDir)) &&
    typeof exeName === 'string' && /^[^\\/:*?"<>|]+\.exe$/i.test(exeName) && exeName === path.basename(exeName) &&
    logFile !== null && VERSION_RE.test(from || '') && VERSION_RE.test(to || '');
  if (!valid) {
    log('bad_args', {});
    return EXIT.badArgs;
  }

  // 1. wait for the old app to be gone (it quits right after spawning us)
  const deadline = Date.now() + waitMs;
  while (isAlive(pid)) {
    if (Date.now() >= deadline) {
      log('old_still_running', { waitedMs: waitMs });
      return EXIT.oldStillRunning; // nothing touched; the old app is still the running one
    }
    sleep(Math.min(250, waitMs));
  }
  log('old_exited', {});

  if (!isDir(installDir) || !isFile(path.join(installDir, exeName)) || !isFile(path.join(stagedDir, exeName))) {
    log('bad_args', { reason: 'folder_or_exe_missing' });
    if (isFile(path.join(installDir, exeName))) await launch(installDir, exeName, ['--update-failed', to], 'old');
    return EXIT.badArgs;
  }

  // 1b. both folders must be exactly a packaged build (main checked this too; a folder may have changed since)
  const prot = protectedDirs(process.env);
  const installWhy = inspectInstallDir(installDir, exeName, prot);
  const stagedWhy = installWhy === null ? inspectInstallDir(stagedDir, exeName, []) : null;
  if (installWhy !== null || stagedWhy !== null) {
    log('not_an_install_dir', { which: installWhy !== null ? 'install' : 'staged', reason: installWhy || stagedWhy });
    await launch(installDir, exeName, ['--update-failed', to], 'old');
    return EXIT.notAnInstallDir;
  }

  // 2. move the running install aside (an existing .old-<from> is replaced only when it is a packaged build)
  let oldDir = installDir + '.old-' + from;
  if (exists(oldDir) && !removeOldBuild(oldDir, exeName, prot)) oldDir = oldDir + '-' + String(Date.now());
  if (renameWithRetry(installDir, oldDir, retryMs, 'install') !== null) {
    log('install_locked', {});
    await launch(installDir, exeName, ['--update-failed', to], 'old');
    return EXIT.installLocked;
  }

  // 3. move the new build into place
  if (!moveStaged(stagedDir, installDir, retryMs)) {
    log('swap_failed', {});
    if (renameWithRetry(oldDir, installDir, retryMs, 'rollback') !== null) {
      log('rollback_failed', {});
      await launch(oldDir, exeName, ['--update-failed', to], 'old');
      return EXIT.rollbackFailed;
    }
    log('rolled_back', {});
    await launch(installDir, exeName, ['--update-failed', to], 'old');
    return EXIT.swapFailed;
  }
  log('swapped', {});

  // 4. start the new build
  if (!(await launch(installDir, exeName, ['--updated-from', from], 'new'))) {
    const back = renameWithRetry(installDir, stagedDir, retryMs, 'unswap') === null;
    if (!back || renameWithRetry(oldDir, installDir, retryMs, 'rollback') !== null) {
      log('rollback_failed', {});
      await launch(isFile(path.join(installDir, exeName)) ? installDir : oldDir, exeName, ['--update-failed', to], 'old');
      return EXIT.rollbackFailed;
    }
    log('rolled_back', {});
    await launch(installDir, exeName, ['--update-failed', to], 'old');
    return EXIT.relaunchFailed;
  }

  // 5. keep exactly one previous build: delete every other <install>.old-* sibling - only those that are packaged builds
  const parent = path.dirname(installDir);
  const prefix = (path.basename(installDir) + '.old-').toLowerCase();
  let removed = 0;
  let kept = 0;
  try {
    for (const name of fs.readdirSync(parent)) {
      const full = path.join(parent, name);
      if (!name.toLowerCase().startsWith(prefix) || norm(full) === norm(oldDir)) continue;
      if (removeOldBuild(full, exeName, prot)) removed += 1;
      else kept += 1;
    }
  } catch (e) {
    /* best effort */
  }
  log('cleanup', { removed: removed, kept: kept });
  return EXIT.ok;
}

if (require.main === module) {
  main().then(
    function (code) {
      log('updater_exit', { code: code });
      process.exit(code);
    },
    function (e) {
      log('updater_crash', { name: (e && e.name) || 'unknown' });
      process.exit(EXIT.rollbackFailed);
    },
  );
} else {
  module.exports = { inspectInstallDir: inspectInstallDir, protectedDirs: protectedDirs, minimalEnv: minimalEnv };
}
`;
